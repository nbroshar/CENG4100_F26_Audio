#!/usr/bin/env python3
"""gen_data.py -- golden data for Case 3 (audio filter).

Makes a block of 1,024 audio samples (16-bit), a 16-tap boost filter with a
gain of about 3, and the exact output the customer's algorithm defines:

    y[n] = saturate_16( (sum over k of h[k] * x[n-k]) >> 15 )

with the sum computed exactly (no overflow), x[n-k] = 0 before the block
starts, ">>" rounding toward minus infinity, and saturation to -32768..32767.
Writes data.h. You do not need to run this; data.h is already generated.
"""

import math
from pathlib import Path

N, TAPS, GAIN = 1024, 16, 3.0


def main():
    # Boost filter: windowed low-pass, scaled so the taps sum to GAIN in Q15.
    raw = []
    for k in range(TAPS):
        t = k - (TAPS - 1) / 2
        sinc = 1.0 if t == 0 else math.sin(math.pi * 0.35 * t) / (math.pi * 0.35 * t)
        window = 0.54 - 0.46 * math.cos(2 * math.pi * k / (TAPS - 1))
        raw.append(sinc * window)
    scale = GAIN * 32768 / sum(raw)
    h = [int(round(v * scale)) for v in raw]
    assert all(-32768 <= v <= 32767 for v in h), "a tap does not fit in 16 bits"

    # Test signal: speech-like tones, plus loud bursts that drive the filter
    # past the range of a 32-bit accumulator and into the output limiter.
    x = []
    for n in range(N):
        v = 9000 * math.sin(2 * math.pi * n / 37) + 5000 * math.sin(2 * math.pi * n / 11)
        if 300 <= n < 340 or 700 <= n < 730:
            v = 32767 if (n // 8) % 2 == 0 else -32768
        x.append(max(-32768, min(32767, int(round(v)))))

    y, int32_wrong = [], 0
    for n in range(N):
        acc = sum(h[k] * x[n - k] for k in range(TAPS) if n - k >= 0)
        y.append(max(-32768, min(32767, acc >> 15)))
        wrapped = ((acc + 2**31) % 2**32) - 2**31          # what an int32 sum would hold
        if max(-32768, min(32767, wrapped >> 15)) != y[-1]:
            int32_wrong += 1
    assert int32_wrong > 0, "test signal should overflow a 32-bit accumulator"

    def arr(name, values):
        rows = [", ".join(str(v) for v in values[i:i + 16]) for i in range(0, len(values), 16)]
        return f"static const int16_t {name}[] = {{\n    " + ",\n    ".join(rows) + "\n};\n"

    out = Path(__file__).with_name("data.h")
    out.write_text(
        "/* data.h -- generated by gen_data.py. Do not edit. */\n"
        "#ifndef CASE3_DATA_H\n#define CASE3_DATA_H\n#include <stdint.h>\n\n"
        f"#define N_SAMPLES {N}\n#define N_TAPS    {TAPS}\n\n"
        + arr("coeffs", h) + "\n" + arr("input", x) + "\n" + arr("expected", y)
        + "\n#endif\n")
    clipped = sum(1 for v in y if v in (32767, -32768))
    print(f"wrote {out}: taps sum {sum(h)}, {clipped} outputs saturated, "
          f"{int32_wrong} outputs a 32-bit accumulator would get wrong")


if __name__ == "__main__":
    main()
